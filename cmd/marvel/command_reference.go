package main

import (
	"fmt"
	"strings"

	"github.com/spf13/cobra"
)

// commandReference renders one markdown page per visible command of the cobra
// tree rooted at root. The key is the page file name, the value is its
// content. The output depends on the tree alone: no date, no host, no
// generator stamp.
//
// Stub: a deliberately wrong answer, so each test fails at its own check
// rather than at the shared "no pages" guard. It returns only the root page,
// stamps it with an auto-generation line, and changes the content on every
// call. The generator replaces it in the next commit, after a second seat has
// run these tests.
var stubReferenceCalls int

func commandReference(root *cobra.Command) map[string]string {
	stubReferenceCalls++
	return map[string]string{
		strings.ReplaceAll(root.CommandPath(), " ", "_") + ".md": fmt.Sprintf("## %s\n\nAuto generated by spf13/cobra, call %d\n", root.CommandPath(), stubReferenceCalls),
	}
}
